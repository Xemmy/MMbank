package com.xemmy.mmbank.domain.report

import java.math.BigDecimal
import java.math.RoundingMode
import java.util.Locale

/**
 * Renders a [MonthlyReport] as a self-contained HTML document.
 *
 * HTML rather than PDF on purpose: it needs no new dependency, it opens in any
 * browser (and prints to PDF from there), and — the deciding factor — it keeps
 * this a pure `MonthlyReport -> String` function that CI can actually test.
 * A PDF renderer would need `android.graphics`, which the JVM unit tests this
 * project relies on cannot exercise.
 *
 * Every interpolated value goes through [escape]: merchant and category names
 * come from captured bank messages, so a name containing `<` or `&` must not be
 * able to corrupt the document.
 */
object MonthlyReportHtmlFormatter {

    fun format(report: MonthlyReport): String = buildString {
        append("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n")
        append("<meta charset=\"utf-8\">\n")
        append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
        append("<title>${escape(report.monthLabel)} — MMbank</title>\n")
        append("<style>\n").append(STYLES).append("\n</style>\n</head>\n<body>\n")

        append("<h1>${escape(report.monthLabel)}</h1>\n")
        append("<p class=\"sub\">${report.transactionCount} transactions · ${escape(report.currency)}</p>\n")

        appendSummary(report)
        appendNetWorth(report)
        appendCategories(report)
        appendMerchants(report)
        appendSubscriptions(report)
        appendGoals(report)
        appendHealth(report)

        append("<p class=\"footer\">Generated by MMbank. Figures cover ")
        append(escape(report.currency))
        append(" only; balance adjustments and cashback are excluded from spending totals.</p>\n")
        append("</body>\n</html>\n")
    }

    private fun StringBuilder.appendSummary(report: MonthlyReport) {
        append("<div class=\"tiles\">\n")
        appendTile("Income", money(report.income, report.currency), delta(report.incomeDelta, report.currency, higherIsBetter = true))
        appendTile("Spent", money(report.spent, report.currency), delta(report.spentDelta, report.currency, higherIsBetter = false))
        appendTile("Net", money(report.net, report.currency), null)
        append("</div>\n")
    }

    private fun StringBuilder.appendTile(label: String, value: String, deltaHtml: String?) {
        append("<div class=\"tile\"><div class=\"label\">${escape(label)}</div>")
        append("<div class=\"value\">${escape(value)}</div>")
        if (deltaHtml != null) append(deltaHtml)
        append("</div>\n")
    }

    /**
     * A delta needs a direction to be readable: more income is good, more spend
     * is not, so the same arrow can't carry the same color for both.
     */
    private fun delta(amount: BigDecimal?, currency: String, higherIsBetter: Boolean): String? {
        if (amount == null || amount.signum() == 0) return null
        val up = amount.signum() > 0
        val good = up == higherIsBetter
        val arrow = if (up) "▲" else "▼"
        val text = "$arrow ${money(amount.abs(), currency)} vs last month"
        return "<div class=\"delta ${if (good) "good" else "bad"}\">${escape(text)}</div>"
    }

    private fun StringBuilder.appendNetWorth(report: MonthlyReport) {
        val netWorth = report.netWorth ?: return
        append("<h2>Net worth</h2>\n<table>\n")
        appendRow("Assets", money(netWorth.debitTotal, report.currency))
        appendRow("Liabilities", money(netWorth.creditTotal, report.currency))
        appendRow("Net worth", money(netWorth.netWorth, report.currency), strong = true)
        append("</table>\n")
    }

    private fun StringBuilder.appendCategories(report: MonthlyReport) {
        if (report.topCategories.isEmpty()) return
        append("<h2>Where it went</h2>\n<table>\n")
        report.topCategories.forEach { line ->
            val share = (line.shareOfSpend * 100).roundToWhole()
            // escape() is mandatory on every rawLabel path: a custom category
            // name is user-supplied text going into markup.
            appendRow(
                "${escape(line.name)} <span class=\"muted\">$share%</span>",
                money(line.amount, report.currency),
                rawLabel = true,
            )
        }
        append("</table>\n")
    }

    private fun StringBuilder.appendMerchants(report: MonthlyReport) {
        if (report.topMerchants.isEmpty()) return
        append("<h2>Top merchants</h2>\n<table>\n")
        report.topMerchants.forEach { line ->
            val label = "${escape(line.name)} <span class=\"muted\">×${line.transactionCount}</span>"
            appendRow(label, money(line.amount, report.currency), rawLabel = true)
        }
        append("</table>\n")
    }

    private fun StringBuilder.appendSubscriptions(report: MonthlyReport) {
        if (report.subscriptions.isEmpty()) return
        append("<h2>Subscriptions</h2>\n<table>\n")
        report.subscriptions.forEach { subscription ->
            val changed = subscription.previousAmount?.let { previous ->
                val rose = subscription.averageAmount > previous
                " <span class=\"${if (rose) "bad" else "good"}\">" +
                    escape((if (rose) "↑ was " else "↓ was ") + money(previous, subscription.currencyCode)) +
                    "</span>"
            }.orEmpty()
            appendRow(
                escape(subscription.merchant) + changed,
                money(subscription.averageAmount, subscription.currencyCode),
                rawLabel = true,
            )
        }
        appendRow("Monthly equivalent", money(report.subscriptionMonthlyTotal, report.currency), strong = true)
        append("</table>\n")
    }

    private fun StringBuilder.appendGoals(report: MonthlyReport) {
        if (report.goals.isEmpty()) return
        append("<h2>Savings goals</h2>\n<table>\n")
        report.goals.forEach { goal ->
            val percent = (goal.progressFraction * 100).roundToWhole()
            appendRow(
                "${escape(goal.icon)} ${escape(goal.title)} <span class=\"muted\">$percent%</span>",
                "${money(goal.currentAmount, report.currency)} / ${money(goal.targetAmount, report.currency)}",
                rawLabel = true,
            )
        }
        append("</table>\n")
    }

    private fun StringBuilder.appendHealth(report: MonthlyReport) {
        val health = report.health ?: return
        append("<h2>Financial health</h2>\n<table>\n")
        appendRow("Savings rate", "${health.savingsRatePercent.roundToWhole()}%")
        health.cashRunwayMonths?.let {
            appendRow("Cash runway", String.format(Locale.US, "%.1f months", it))
        }
        append("</table>\n")
    }

    private fun StringBuilder.appendRow(
        label: String,
        value: String,
        strong: Boolean = false,
        rawLabel: Boolean = false,
    ) {
        val cell = if (strong) "th" else "td"
        append("<tr><$cell>")
        append(if (rawLabel) label else escape(label))
        append("</$cell><$cell class=\"num\">")
        append(escape(value))
        append("</$cell></tr>\n")
    }

    private fun money(amount: BigDecimal, currency: String): String =
        "${amount.setScale(2, RoundingMode.HALF_UP).toPlainString()} ${currency.uppercase()}"

    private fun Double.roundToWhole(): Long =
        BigDecimal(this).setScale(0, RoundingMode.HALF_UP).toLong()

    /** Escapes the five characters that can break out of HTML text or an attribute. */
    internal fun escape(value: String): String = buildString(value.length) {
        value.forEach { char ->
            when (char) {
                '&' -> append("&amp;")
                '<' -> append("&lt;")
                '>' -> append("&gt;")
                '"' -> append("&quot;")
                '\'' -> append("&#39;")
                else -> append(char)
            }
        }
    }

    private val STYLES = """
        :root { color-scheme: light dark; }
        body {
          font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
          margin: 0 auto; padding: 24px; max-width: 720px; line-height: 1.5;
          background: #ffffff; color: #16181d;
        }
        h1 { font-size: 1.6rem; margin: 0 0 4px; }
        h2 { font-size: 1.05rem; margin: 28px 0 8px; text-transform: uppercase;
             letter-spacing: .08em; color: #6b7280; }
        .sub { margin: 0 0 20px; color: #6b7280; font-size: .9rem; }
        .tiles { display: flex; gap: 12px; flex-wrap: wrap; }
        .tile { flex: 1 1 150px; border: 1px solid rgba(0,0,0,.1); border-radius: 12px; padding: 12px 14px; }
        .tile .label { font-size: .75rem; text-transform: uppercase; letter-spacing: .08em; color: #6b7280; }
        .tile .value { font-size: 1.25rem; font-weight: 600; margin-top: 2px; }
        .delta { font-size: .78rem; margin-top: 4px; }
        .good { color: #12805c; }
        .bad { color: #b3261e; }
        .muted { color: #6b7280; font-weight: 400; font-size: .85em; }
        table { width: 100%; border-collapse: collapse; }
        td, th { text-align: left; padding: 7px 0; border-bottom: 1px solid rgba(0,0,0,.07); font-weight: 400; }
        th { font-weight: 600; border-bottom: none; }
        .num { text-align: right; font-variant-numeric: tabular-nums; white-space: nowrap; }
        .footer { margin-top: 32px; font-size: .78rem; color: #6b7280; }
        @media (prefers-color-scheme: dark) {
          body { background: #0f1115; color: #e8eaed; }
          .tile { border-color: rgba(255,255,255,.14); }
          td, th { border-bottom-color: rgba(255,255,255,.1); }
          .good { color: #6ee7b7; }
          .bad { color: #fca5a5; }
        }
    """.trimIndent()
}
